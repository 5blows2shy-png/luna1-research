import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('CloudSpend connects financial and operational workflows on desktop and mobile', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/applied-projects');
  await page.getByRole('link', { name: 'Launch Luna1 CloudSpend', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Every resource. Every dollar.' })).toBeVisible();
  const nav = page.getByRole('navigation', { name: 'CloudSpend views' });
  await page.getByRole('combobox', { name: 'Cloud provider', exact: true }).selectOption('AWS');
  await expect(page.getByRole('region', { name: 'Top five workloads', exact: true })).not.toContainText('-azure');
  await page.getByRole('combobox', { name: 'Cloud provider', exact: true }).selectOption('All');
  await page.getByRole('heading', { name: 'Every resource. Every dollar.' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `/tmp/cloudspend-overview-${test.info().project.name}.png`, fullPage: true });
  await nav.getByRole('button', { name: 'Resource intelligence', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Virtual machine rightsizing', exact: true })).toContainText('Keep current size');
  await page.getByRole('button', { name: 'analytics-worker-aws', exact: false }).click();
  await expect(page.getByText('Memory demand or pressure blocks reduction')).toBeVisible();
  await nav.getByRole('button', { name: 'Allocation & showback', exact: true }).click();
  await page.getByRole('combobox', { name: 'Allocate by', exact: true }).selectOption('Project');
  await expect(page.getByRole('region', { name: 'Showback by allocation group', exact: true })).toContainText('Unallocated');
  const [showback] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download monthly showback' }).click()]);
  expect(await readFile((await showback.path())!, 'utf8')).toContain('"Project"');
  await nav.getByRole('button', { name: 'Planning & forecasts', exact: true }).click();
  const bridge = page.getByRole('region', { name: 'Forecast versus hypothetical savings', exact: true });
  const before = await bridge.textContent();
  await page.getByLabel('Monthly workload growth (%)').fill('10');
  await expect(bridge).not.toHaveText(before!);
  await page.getByLabel('Expected savings (%)').fill('0');
  await page.getByLabel('Monthly budget for this scope ($)').fill('50000');
  await expect(bridge).toContainText('$50,000');
  await nav.getByRole('button', { name: /Cost anomalies/ }).click();
  await expect(page.getByRole('heading', { name: 'AWS · Compute cost increase' })).toBeVisible();
  const status = page.getByRole('combobox', { name: 'Review status for AWS Compute 2026-11-18', exact: true });
  await status.selectOption('Investigating'); await expect(status).toHaveValue('Investigating');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('CloudSpend local CSV import validates atomically and withholds unsupported telemetry', async ({ page }) => {
  const header = 'ProviderName,ServiceCategory,ServiceName,ResourceId,ChargePeriodStart,ChargePeriodEnd,BilledCost,EffectiveCost,BillingCurrency,x_Department';
  const fixture = `${header}\nAWS,Compute,EC2,imported-vm,2026-11-01T00:00:00Z,2026-11-02T00:00:00Z,123,100,USD,Engineering`;
  await page.goto('/cloudspend');
  const nav = page.getByRole('navigation', { name: 'CloudSpend views' });
  await nav.getByRole('button', { name: 'Data & methodology', exact: true }).click();
  await page.getByLabel('Coverage start', { exact: true }).fill('2026-11-01');
  await page.getByLabel('Data complete through', { exact: true }).fill('2026-11-01');
  await page.getByLabel('FOCUS billing CSV', { exact: true }).setInputFiles({ name: 'focus.csv', mimeType: 'text/csv', buffer: Buffer.from(fixture) });
  await expect(page.getByRole('status')).toContainText('Imported 1 records');
  await page.getByLabel('FOCUS billing CSV', { exact: true }).setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from(fixture.replace(',USD,', ',EUR,')) });
  await expect(page.getByRole('alert').filter({ hasText: 'Only USD' })).toContainText('Only USD');
  await nav.getByRole('button', { name: 'Overview', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Top five workloads', exact: true })).toContainText('imported-vm');
  await expect(page.getByRole('region', { name: 'Top five workloads', exact: true })).toContainText('$123');
  await nav.getByRole('button', { name: 'Resource intelligence', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Utilization evidence unavailable' })).toBeVisible();
  await page.reload();
  await expect(page.getByText('SIMULATED ENVIRONMENT', { exact: true })).toBeVisible();
});
