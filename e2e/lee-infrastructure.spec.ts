import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('Lee sourcing and power tabs recalculate and export from the current 10 MW model', async ({ page, request }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/recruiter/projects/lee-data-center');
  await page.getByRole('button', { name: 'Infrastructure options', exact: true }).click();
  const comparison = page.getByRole('region', { name: 'Infrastructure sourcing cost comparison', exact: true });
  await expect(comparison).toContainText('Owned infrastructure');
  const before = await comparison.textContent();
  await page.getByText('Edit infrastructure comparison assumptions', { exact: true }).click();
  await page.getByLabel('Cloud compute including 4 GB RAM / vCPU ($/hour)', { exact: true }).fill('0.09');
  await expect(comparison).not.toHaveText(before!);
  await page.getByLabel('Hardware refresh cycle (years)', { exact: true }).fill('0');
  await expect(page.getByRole('alert').filter({ hasText: 'Outputs withheld' })).toBeVisible();
  await expect(comparison).toHaveCount(0);
  await page.getByRole('button', { name: 'Reset comparison assumptions', exact: true }).click();
  await expect(comparison).toHaveText(before!);
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download comparison annual CSV' }).click()]);
  const csv = await readFile((await download.path())!, 'utf8');
  expect(csv).toContain('"Hardware_CapEx"'); expect(csv).toContain('"Colocation"');
  await page.getByRole('button', { name: 'Power pricing', exact: true }).click();
  const power = page.getByRole('region', { name: 'Power-price investment sensitivity', exact: true });
  await expect(power).toContainText('$0.0750 · current');
  await page.getByText('Edit investment & financing assumptions', { exact: true }).click();
  await page.getByLabel('Power price ($/kWh)', { exact: true }).fill('0.0825');
  await expect(power).toContainText('$0.0825 · current');
  await page.getByText('Edit investment & financing assumptions', { exact: true }).click();
  await page.getByRole('heading', { name: 'What does a higher electricity price do to the investment?' }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `/tmp/lee-power-${test.info().project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Power BI', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'The current model, in Power BI.' })).toBeVisible();
  await expect(page.getByText('The downloadable PBIP is the earlier 20 MW teaching case.', { exact: false })).toHaveCount(0);
  const link = page.getByRole('link', { name: 'Download current 10 MW Power BI report project →' });
  const zip = await request.get((await link.getAttribute('href'))!); expect(zip.ok()).toBe(true); expect((await zip.body()).subarray(0,2).toString()).toBe('PK');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
